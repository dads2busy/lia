#!/usr/bin/env python3
"""Turn eval CSVs into LaTeX macros (eval_numbers.tex) and tables (eval_tables.tex).

Usage: python scripts/eval/make_latex.py --data-dir "$DATA" \
          [--folder LABEL PATH [--folder LABEL PATH ...]] [--primary-judge claude]

--folder LABEL PATH (repeatable, optional) points at a MEKH's research_state.json
folder (e.g. "$STATE_B"); when given, also emits \\MekhMaterials<Label> /
\\MekhProcesses<Label> / gate-audit macros and writes "$DATA/mekh_sizes.csv".

--primary-judge JUDGE (default "claude") selects which judge's per-label record
count backs \\JudgeN<Label> / \\JudgeNAll: judges can skip different records on
failure, so their n's can disagree and an arbitrary pick would be wrong.
"""
from __future__ import annotations
import argparse, csv, json, re, sys
from pathlib import Path

SIX_DIGIT = re.compile(r"^\d{6}$")

def cap(label: str) -> str: return label[:1].upper() + label[1:]
def pct(x: float) -> str: return f"{round(float(x) * 100)}\\%"
def macro(name: str, label: str, value) -> str: return f"\\newcommand{{\\{name}{cap(label)}}}{{{value}}}"
def _read(p: Path) -> list[dict]:
    return list(csv.DictReader(open(p, newline=""))) if p.exists() else []

def _primary_n(rows: list[dict], primary_judge: str) -> int:
    """Record count backing \\JudgeN<Label>: the primary judge's n when present,
    else the sole judge's n when there is only one, else the first row's (ambiguous)."""
    by_judge = {r["judge"]: int(r["n"]) for r in rows}
    if primary_judge in by_judge:
        return by_judge[primary_judge]
    if len(by_judge) == 1:
        return next(iter(by_judge.values()))
    return int(rows[0]["n"])

def build_numbers(d: Path, primary_judge: str = "claude", process_counts: dict[str, int] | None = None) -> str:
    L = []
    js = _read(d / "judge_summary.csv")
    for r in js:
        j = cap(r["judge"]); l = r["label"]
        L += [macro("JudgeN", l + j, r["n"]),
              macro("JudgePrecision", l + j, pct(r["precision"])),
              macro("JudgeCILo", l + j, pct(r["ci_lo"])), macro("JudgeCIHi", l + j, pct(r["ci_hi"])),
              macro("JudgePlausible", l + j, pct(r["plausible_rate"])), macro("JudgeIO", l + j, pct(r["io_rate"])),
              macro("JudgeHS", l + j, pct(r["hs_rate"]))]
    labels = sorted({r["label"] for r in js})
    n_all_primary = 0
    for label in labels:
        rows = [r for r in js if r["label"] == label]
        by_judge = {r["judge"]: int(r["n"]) for r in rows}
        n_primary = _primary_n(rows, primary_judge)
        L.append(macro("JudgeN", label, n_primary))
        n_all_primary += n_primary
        if len(set(by_judge.values())) > 1:
            print(f"WARNING: judge_summary.csv label={label!r} judges disagree on n: {by_judge}", file=sys.stderr)
        if process_counts is not None and label in process_counts and process_counts[label] != n_primary:
            print(f"WARNING: judge_summary.csv label={label!r} primary-judge ({primary_judge}) n={n_primary} "
                  f"!= MEKH process count {process_counts[label]}", file=sys.stderr)
    if js:
        L.append(macro("JudgeN", "all", n_all_primary))
    for judge in sorted({r["judge"] for r in js}):
        rows = [r for r in js if r["judge"] == judge]; n = sum(int(r["n"]) for r in rows)
        ok = sum(int(r["overall_correct"]) for r in rows)
        L += [macro("JudgePrecision", "all" + cap(judge), pct(ok / n if n else 0.0)),
              macro("JudgeN", "all" + cap(judge), n)]
    for r in _read(d / "judge_agreement.csv"):
        L += [macro("JudgeKappa", r["label"], f"{float(r['cohen_kappa']):.2f}"), macro("JudgeAgreement", r["label"], pct(r["agreement"]))]
    for r in _read(d / "evidence_support.csv"):
        L += [macro("EvidenceFull", r["label"], pct(r["frac_full"])), macro("EvidenceAny", r["label"], pct(r["frac_any"])),
              macro("EvidenceRefsFetched", r["label"], pct(r["frac_refs_with_content"])), macro("EvidenceNRefs", r["label"], r["n_refs"])]
    for r in _read(d / "known_route_recall.csv"):
        L += [macro("RoutesN", r["label"], r["n_routes"]), macro("RecallLenient", r["label"], pct(r["recall_lenient"])),
              macro("RecallStrict", r["label"], pct(r["recall_strict"]))]
    for r in _read(d / "topdown_coverage.csv"):
        L += [macro("CoverageMekhOnly", r["label"], r["mekh_only"]), macro("CoverageFrac", r["label"], pct(r["frac_mekh_only"])),
              macro("CoverageUsgs", r["label"], r["usgs_codes"]), macro("CoverageMekh", r["label"], r["mekh_codes"])]
    # \newcommand errors on redefinition; keep the first line seen for any macro name (defensive dedupe).
    seen: dict[str, str] = {}
    for line in L:
        name = line.split("}{", 1)[0]
        seen.setdefault(name, line)
    return "% generated by scripts/eval/make_latex.py -- do not edit\n" + "\n".join(seen.values()) + "\n"

def _hs_class(entry, materials: dict) -> str:
    """Classify a precursor/product entry: "untyped" if it's a bare string or has
    a missing/"Unknown"/non-6-digit hs_code (no type information at all);
    "unregistered" if it has a well-formed 6-digit hs_code that just isn't a key
    of state["materials"] (typed, but not a registered vertex); else "ok"."""
    if not isinstance(entry, dict):
        return "untyped"
    code = entry.get("hs_code")
    if not code or code == "Unknown" or not SIX_DIGIT.match(str(code)):
        return "untyped"
    return "unregistered" if str(code) not in materials else "ok"

def gate_audit(state: dict) -> dict:
    """Count process-level gate-audit issues in a research_state.json dict:
    unscored (process_score is None), below-tau (score defined but < 0.5, which
    the purge step should already remove), untyped edges (a precursor or product
    that is a bare string or has a missing/malformed hs_code -- no type at all),
    and unregistered edges (a well-formed 6-digit hs_code that isn't a known
    material -- typed, but not a registered vertex). A process can count toward
    both untyped and unregistered if it has one edge of each kind."""
    materials = state.get("materials", {})
    processes = state.get("processes", {})
    n_unscored = n_below_tau = n_untyped_edges = n_unregistered_edges = 0
    for p in processes.values():
        score = p.get("process_score")
        if score is None:
            n_unscored += 1
        elif float(score) < 0.5:
            n_below_tau += 1
        edges = list(p.get("precursors", [])) + list(p.get("products", []))
        classes = {_hs_class(e, materials) for e in edges}
        if "untyped" in classes:
            n_untyped_edges += 1
        if "unregistered" in classes:
            n_unregistered_edges += 1
    return {"n_processes": len(processes), "n_unscored": n_unscored, "n_below_tau": n_below_tau,
            "n_untyped_edges": n_untyped_edges, "n_unregistered_edges": n_unregistered_edges}

def mekh_sizes(folders: list[tuple[str, Path]]) -> list[dict]:
    """Given (label, state-folder) pairs, return size + gate-audit rows:
    [{label, n_materials, n_processes, n_unscored, n_below_tau, n_untyped_edges,
      n_unregistered_edges}, ...]."""
    rows = []
    for label, path in folders:
        state = json.loads((Path(path) / "research_state.json").read_text())
        audit = gate_audit(state)
        rows.append({"label": label, "n_materials": len(state.get("materials", {})), **audit})
    return rows

def build_size_numbers(rows: list[dict]) -> str:
    L = []
    for r in rows:
        n_proc = r["n_processes"]
        L += [macro("MekhMaterials", r["label"], r["n_materials"]),
              macro("MekhProcesses", r["label"], n_proc),
              macro("MekhUnscored", r["label"], r["n_unscored"]),
              macro("MekhBelowTau", r["label"], r["n_below_tau"]),
              macro("MekhUntypedEdges", r["label"], r["n_untyped_edges"]),
              macro("MekhUnregisteredEdges", r["label"], r["n_unregistered_edges"]),
              macro("MekhUnscoredFrac", r["label"], pct(r["n_unscored"] / n_proc if n_proc else 0.0)),
              macro("MekhUntypedEdgesFrac", r["label"], pct(r["n_untyped_edges"] / n_proc if n_proc else 0.0)),
              macro("MekhUnregisteredEdgesFrac", r["label"], pct(r["n_unregistered_edges"] / n_proc if n_proc else 0.0))]
    if rows:
        L += [macro("MekhProcesses", "all", sum(r["n_processes"] for r in rows)),
              macro("MekhUnscored", "all", sum(r["n_unscored"] for r in rows)),
              macro("MekhUntypedEdges", "all", sum(r["n_untyped_edges"] for r in rows)),
              macro("MekhUnregisteredEdges", "all", sum(r["n_unregistered_edges"] for r in rows))]
    return "\n".join(L) + ("\n" if L else "")

def write_mekh_sizes_csv(rows: list[dict], path: Path) -> None:
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["label", "n_materials", "n_processes", "n_unscored",
                                           "n_below_tau", "n_untyped_edges", "n_unregistered_edges"])
        w.writeheader()
        w.writerows(rows)

def build_tables(d: Path) -> str:
    T = []
    js = _read(d / "judge_summary.csv"); ag = {r["label"]: r for r in _read(d / "judge_agreement.csv")}
    if js:
        T += [r"\begin{table}[t]\centering\small", r"\caption{RQ1 precision proxy: fraction of hyperedges judged fully correct (process, inputs/outputs, HS codes) by two independent LLM judges, with bootstrap 95\% CIs and inter-judge agreement ($\kappa$).}",
              r"\label{tab:judge}", r"\begin{tabular}{llrrrr}\toprule", r"MEKH & Judge & $n$ & Precision & 95\% CI & $\kappa$ \\\midrule"]
        for r in js:
            T.append(f"{cap(r['label'])} & {r['judge']} & {r['n']} & {pct(r['precision'])} & [{pct(r['ci_lo'])}, {pct(r['ci_hi'])}] & {float(ag[r['label']]['cohen_kappa']):.2f} \\\\" if r['label'] in ag
                     else f"{cap(r['label'])} & {r['judge']} & {r['n']} & {pct(r['precision'])} & [{pct(r['ci_lo'])}, {pct(r['ci_hi'])}] & -- \\\\")
        T += [r"\bottomrule\end{tabular}\end{table}", ""]
    ev = _read(d / "evidence_support.csv")
    if ev:
        T += [r"\begin{table}[t]\centering\small", r"\caption{Evidence grounding: share of hyperedges whose cited references mention at least one input and one output (fully grounded), any input or output, and share of references with retrievable content.}",
              r"\label{tab:evidence}", r"\begin{tabular}{lrrrr}\toprule", r"MEKH & Refs & Retrievable & Any mention & Fully grounded \\\midrule"]
        T += [f"{cap(r['label'])} & {r['n_refs']} & {pct(r['frac_refs_with_content'])} & {pct(r['frac_any'])} & {pct(r['frac_full'])} \\\\" for r in ev]
        T += [r"\bottomrule\end{tabular}\end{table}", ""]
    rc = _read(d / "known_route_recall.csv")
    if rc:
        T += [r"\begin{table}[t]\centering\small", r"\caption{Recall of author-curated canonical routes (lenient: shared input and output code; strict: route codes $\subseteq$ hyperedge codes).}",
              r"\label{tab:recall}", r"\begin{tabular}{lrrr}\toprule", r"MEKH & Routes & Lenient & Strict \\\midrule"]
        T += [f"{cap(r['label'])} & {r['n_routes']} & {pct(r['recall_lenient'])} & {pct(r['recall_strict'])} \\\\" for r in rc]
        T += [r"\bottomrule\end{tabular}\end{table}", ""]
    cv = _read(d / "topdown_coverage.csv")
    if cv:
        T += [r"\begin{table}[t]\centering\small", r"\caption{RQ2: HS-6 codes in each MEKH versus the codes listed for the commodity in the USGS Mineral Commodity Summaries (top-down view).}",
              r"\label{tab:coverage}", r"\begin{tabular}{lrrrr}\toprule", r"MEKH & MEKH codes & USGS codes & Overlap & MEKH-only \\\midrule"]
        T += [f"{cap(r['label'])} & {r['mekh_codes']} & {r['usgs_codes']} & {r['overlap']} & {r['mekh_only']} ({pct(r['frac_mekh_only'])}) \\\\" for r in cv]
        T += [r"\bottomrule\end{tabular}\end{table}", ""]
    return "\n".join(T)

def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-dir", type=Path, required=True)
    ap.add_argument("--folder", nargs=2, action="append", metavar=("LABEL", "PATH"), default=[])
    ap.add_argument("--primary-judge", default="claude")
    a = ap.parse_args()
    rows = None
    process_counts = None
    if a.folder:
        rows = mekh_sizes([(label, Path(path)) for label, path in a.folder])
        process_counts = {r["label"]: r["n_processes"] for r in rows}
    numbers = build_numbers(a.data_dir, primary_judge=a.primary_judge, process_counts=process_counts)
    if rows is not None:
        numbers += build_size_numbers(rows)
        write_mekh_sizes_csv(rows, a.data_dir / "mekh_sizes.csv")
    (a.data_dir / "eval_numbers.tex").write_text(numbers)
    (a.data_dir / "eval_tables.tex").write_text(build_tables(a.data_dir))
    print("wrote", a.data_dir / "eval_numbers.tex", a.data_dir / "eval_tables.tex")

if __name__ == "__main__":
    main()
