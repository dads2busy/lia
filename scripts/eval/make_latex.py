#!/usr/bin/env python3
"""Turn eval CSVs into LaTeX macros (eval_numbers.tex) and tables (eval_tables.tex).

Usage: python scripts/eval/make_latex.py --data-dir "$DATA" \
          [--folder LABEL PATH [--folder LABEL PATH ...]]

--folder LABEL PATH (repeatable, optional) points at a MEKH's research_state.json
folder (e.g. "$STATE_B"); when given, also emits \\MekhMaterials<Label> /
\\MekhProcesses<Label> macros and writes "$DATA/mekh_sizes.csv".
"""
from __future__ import annotations
import argparse, csv, json
from pathlib import Path

def cap(label: str) -> str: return label[:1].upper() + label[1:]
def pct(x: float) -> str: return f"{round(float(x) * 100)}\\%"
def macro(name: str, label: str, value) -> str: return f"\\newcommand{{\\{name}{cap(label)}}}{{{value}}}"
def _read(p: Path) -> list[dict]:
    return list(csv.DictReader(open(p, newline=""))) if p.exists() else []

def build_numbers(d: Path) -> str:
    L = []
    js = _read(d / "judge_summary.csv")
    for r in js:
        j = cap(r["judge"]); l = r["label"]
        L += [macro("JudgeN", l, r["n"]), macro("JudgePrecision", l + j, pct(r["precision"])),
              macro("JudgeCILo", l + j, pct(r["ci_lo"])), macro("JudgeCIHi", l + j, pct(r["ci_hi"])),
              macro("JudgePlausible", l + j, pct(r["plausible_rate"])), macro("JudgeIO", l + j, pct(r["io_rate"])),
              macro("JudgeHS", l + j, pct(r["hs_rate"]))]
    for judge in sorted({r["judge"] for r in js}):
        rows = [r for r in js if r["judge"] == judge]; n = sum(int(r["n"]) for r in rows)
        ok = sum(int(r["overall_correct"]) for r in rows)
        L += [macro("JudgePrecision", "all" + cap(judge), pct(ok / n if n else 0.0)), macro("JudgeN", "all", n)]
    for r in _read(d / "judge_agreement.csv"):
        L += [macro("JudgeKappa", r["label"], f"{float(r['cohen_kappa']):.2f}"), macro("JudgeAgreement", r["label"], pct(r["agreement"]))]
    for r in _read(d / "evidence_support.csv"):
        L += [macro("EvidenceFull", r["label"], pct(r["frac_full"])), macro("EvidenceAny", r["label"], pct(r["frac_any"])),
              macro("EvidenceRefsFetched", r["label"], pct(r["frac_refs_with_content"])), macro("EvidenceNRefs", r["label"], r["n_refs"])]
    for r in _read(d / "known_route_recall.csv"):
        L += [macro("RoutesN", r["label"], r["n_routes"]), macro("RecallLenient", r["label"], pct(r["recall_lenient"])),
              macro("RecallStrict", r["label"], pct(r["recall_strict"]))]
    for r in _read(d / "topdown_coverage.csv"):
        L += [macro("CoverageMekhOnly", r["label"], r["mekh_only"]), macro("CoverageFrac", r["label"], pct(r["frac_mekh_only"])),
              macro("CoverageUsgs", r["label"], r["usgs_codes"]), macro("CoverageMekh", r["label"], r["mekh_codes"])]
    # \newcommand errors on redefinition, and JudgeN<Label> / JudgeNAll are emitted once per judge: keep the first of each name.
    seen: dict[str, str] = {}
    for line in L:
        name = line.split("}{", 1)[0]
        seen.setdefault(name, line)
    return "% generated by scripts/eval/make_latex.py -- do not edit\n" + "\n".join(seen.values()) + "\n"

def mekh_sizes(folders: list[tuple[str, Path]]) -> list[dict]:
    """Given (label, state-folder) pairs, return [{label, n_materials, n_processes}, ...]."""
    rows = []
    for label, path in folders:
        state = json.loads((Path(path) / "research_state.json").read_text())
        rows.append({"label": label, "n_materials": len(state.get("materials", {})), "n_processes": len(state.get("processes", {}))})
    return rows

def build_size_numbers(rows: list[dict]) -> str:
    L = []
    for r in rows:
        L += [macro("MekhMaterials", r["label"], r["n_materials"]), macro("MekhProcesses", r["label"], r["n_processes"])]
    return "\n".join(L) + ("\n" if L else "")

def write_mekh_sizes_csv(rows: list[dict], path: Path) -> None:
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["label", "n_materials", "n_processes"])
        w.writeheader()
        w.writerows(rows)

def build_tables(d: Path) -> str:
    T = []
    js = _read(d / "judge_summary.csv"); ag = {r["label"]: r for r in _read(d / "judge_agreement.csv")}
    if js:
        T += [r"\begin{table}[t]\centering\small", r"\caption{RQ1 precision proxy: fraction of hyperedges judged fully correct (process, inputs/outputs, HS codes) by two independent LLM judges, with bootstrap 95\% CIs and inter-judge agreement ($\kappa$).}",
              r"\label{tab:judge}", r"\begin{tabular}{llrrrr}\toprule", r"MEKH & Judge & $n$ & Precision & 95\% CI & $\kappa$ \\\midrule"]
        for r in js:
            T.append(f"{cap(r['label'])} & {r['judge']} & {r['n']} & {pct(r['precision'])} & [{pct(r['ci_lo'])}, {pct(r['ci_hi'])}] & {float(ag[r['label']]['cohen_kappa']):.2f} \\\\" if r['label'] in ag
                     else f"{cap(r['label'])} & {r['judge']} & {r['n']} & {pct(r['precision'])} & [{pct(r['ci_lo'])}, {pct(r['ci_hi'])}] & -- \\\\")
        T += [r"\bottomrule\end{tabular}\end{table}", ""]
    ev = _read(d / "evidence_support.csv")
    if ev:
        T += [r"\begin{table}[t]\centering\small", r"\caption{Evidence grounding: share of hyperedges whose cited references mention at least one input and one output (fully grounded), any input or output, and share of references with retrievable content.}",
              r"\label{tab:evidence}", r"\begin{tabular}{lrrrr}\toprule", r"MEKH & Refs & Retrievable & Any mention & Fully grounded \\\midrule"]
        T += [f"{cap(r['label'])} & {r['n_refs']} & {pct(r['frac_refs_with_content'])} & {pct(r['frac_any'])} & {pct(r['frac_full'])} \\\\" for r in ev]
        T += [r"\bottomrule\end{tabular}\end{table}", ""]
    rc = _read(d / "known_route_recall.csv")
    if rc:
        T += [r"\begin{table}[t]\centering\small", r"\caption{Recall of author-curated canonical routes (lenient: shared input and output code; strict: route codes $\subseteq$ hyperedge codes).}",
              r"\label{tab:recall}", r"\begin{tabular}{lrrr}\toprule", r"MEKH & Routes & Lenient & Strict \\\midrule"]
        T += [f"{cap(r['label'])} & {r['n_routes']} & {pct(r['recall_lenient'])} & {pct(r['recall_strict'])} \\\\" for r in rc]
        T += [r"\bottomrule\end{tabular}\end{table}", ""]
    cv = _read(d / "topdown_coverage.csv")
    if cv:
        T += [r"\begin{table}[t]\centering\small", r"\caption{RQ2: HS-6 codes in each MEKH versus the codes listed for the commodity in the USGS Mineral Commodity Summaries (top-down view).}",
              r"\label{tab:coverage}", r"\begin{tabular}{lrrrr}\toprule", r"MEKH & MEKH codes & USGS codes & Overlap & MEKH-only \\\midrule"]
        T += [f"{cap(r['label'])} & {r['mekh_codes']} & {r['usgs_codes']} & {r['overlap']} & {r['mekh_only']} ({pct(r['frac_mekh_only'])}) \\\\" for r in cv]
        T += [r"\bottomrule\end{tabular}\end{table}", ""]
    return "\n".join(T)

def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-dir", type=Path, required=True)
    ap.add_argument("--folder", nargs=2, action="append", metavar=("LABEL", "PATH"), default=[])
    a = ap.parse_args()
    numbers = build_numbers(a.data_dir)
    if a.folder:
        rows = mekh_sizes([(label, Path(path)) for label, path in a.folder])
        numbers += build_size_numbers(rows)
        write_mekh_sizes_csv(rows, a.data_dir / "mekh_sizes.csv")
    (a.data_dir / "eval_numbers.tex").write_text(numbers)
    (a.data_dir / "eval_tables.tex").write_text(build_tables(a.data_dir))
    print("wrote", a.data_dir / "eval_numbers.tex", a.data_dir / "eval_tables.tex")

if __name__ == "__main__":
    main()
